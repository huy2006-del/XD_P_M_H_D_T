-- Apply in freshvend_inventory after the existing fruit_batches and stock_movements tables.
BEGIN;

CREATE TABLE public.restock_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_code VARCHAR(15) NOT NULL,
    machine_id BIGINT NOT NULL,
    operator_id UUID NOT NULL,
    status VARCHAR(16) NOT NULL,
    started_at TIMESTAMPTZ NOT NULL,
    completed_at TIMESTAMPTZ,
    notes TEXT,
    CONSTRAINT uk_restock_sessions_code UNIQUE (session_code),
    CONSTRAINT ck_restock_sessions_code CHECK (
        session_code ~ '^RS-[0-9]{8}-[0-9]{3}$'
        AND right(session_code, 3) <> '000'
    ),
    CONSTRAINT ck_restock_sessions_machine CHECK (machine_id > 0),
    CONSTRAINT ck_restock_sessions_status CHECK (status IN ('IN_PROGRESS', 'COMPLETED', 'CANCELLED')),
    CONSTRAINT ck_restock_sessions_completion CHECK ((status = 'COMPLETED') = (completed_at IS NOT NULL)),
    CONSTRAINT ck_restock_sessions_dates CHECK (completed_at IS NULL OR completed_at >= started_at)
);

CREATE INDEX idx_restock_sessions_machine_history
    ON public.restock_sessions (machine_id, started_at DESC, id DESC);

CREATE TABLE public.restock_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL,
    slot_id BIGINT NOT NULL,
    batch_id BIGINT NOT NULL,
    quantity_added INTEGER NOT NULL,
    slot_code TEXT NOT NULL,
    product_name TEXT NOT NULL,
    batch_code TEXT NOT NULL,
    CONSTRAINT fk_restock_items_session FOREIGN KEY (session_id)
        REFERENCES public.restock_sessions (id) ON DELETE RESTRICT,
    CONSTRAINT fk_restock_items_batch FOREIGN KEY (batch_id)
        REFERENCES public.fruit_batches (id) ON DELETE RESTRICT,
    CONSTRAINT uk_restock_items_session_slot_batch UNIQUE (session_id, slot_id, batch_id),
    CONSTRAINT ck_restock_items_slot CHECK (slot_id > 0),
    CONSTRAINT ck_restock_items_quantity CHECK (quantity_added > 0)
);

CREATE TABLE public.restock_session_daily_counters (
    business_date DATE PRIMARY KEY,
    last_number INTEGER NOT NULL,
    CONSTRAINT ck_restock_session_daily_counters_number CHECK (last_number BETWEEN 1 AND 999)
);

ALTER TABLE public.stock_movements
    DROP CONSTRAINT stock_movements_type_check,
    ADD CONSTRAINT stock_movements_type_check CHECK (type IN ('LOAD', 'RESTOCK', 'DISPENSE'));

COMMIT;
